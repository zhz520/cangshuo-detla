-- 后台可配置轮播主视觉文字
SET @db = DATABASE();
SET @sql = (SELECT IF(COUNT(*)=0, 'ALTER TABLE banner ADD COLUMN title VARCHAR(100) DEFAULT NULL', 'SELECT 1') FROM information_schema.COLUMNS WHERE TABLE_SCHEMA=@db AND TABLE_NAME='banner' AND COLUMN_NAME='title');
PREPARE stmt FROM @sql; EXECUTE stmt; DEALLOCATE PREPARE stmt;
SET @sql = (SELECT IF(COUNT(*)=0, 'ALTER TABLE banner ADD COLUMN subtitle VARCHAR(200) DEFAULT NULL', 'SELECT 1') FROM information_schema.COLUMNS WHERE TABLE_SCHEMA=@db AND TABLE_NAME='banner' AND COLUMN_NAME='subtitle');
PREPARE stmt FROM @sql; EXECUTE stmt; DEALLOCATE PREPARE stmt;
