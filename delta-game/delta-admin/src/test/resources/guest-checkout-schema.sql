DROP TABLE IF EXISTS guest_user_link;
DROP TABLE IF EXISTS guest_checkout_profile;
DROP TABLE IF EXISTS wallet;
DROP TABLE IF EXISTS payment;
DROP TABLE IF EXISTS complaint;
DROP TABLE IF EXISTS `order`;
DROP TABLE IF EXISTS `user`;

CREATE TABLE `user` (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  openid VARCHAR(64) NOT NULL UNIQUE,
  nickname VARCHAR(64) NOT NULL DEFAULT '',
  avatar VARCHAR(512) NOT NULL DEFAULT '',
  phone VARCHAR(20) NOT NULL DEFAULT '',
  password VARCHAR(100),
  auth_version BIGINT NOT NULL DEFAULT 0,
  is_guest TINYINT NOT NULL DEFAULT 0,
  status TINYINT NOT NULL DEFAULT 1,
  deleted TINYINT NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE wallet (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  user_id BIGINT NOT NULL UNIQUE,
  balance DECIMAL(12,2) NOT NULL DEFAULT 0,
  frozen_amount DECIMAL(12,2) NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE guest_checkout_profile (
  user_id BIGINT PRIMARY KEY,
  phone_hash CHAR(64) NOT NULL,
  phone_mask VARCHAR(20) NOT NULL,
  lookup_hash CHAR(64) NOT NULL,
  privacy_version VARCHAR(32) NOT NULL DEFAULT '',
  privacy_accepted_at TIMESTAMP,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE(phone_hash)
);

CREATE TABLE guest_user_link (
  guest_user_id BIGINT PRIMARY KEY,
  registered_user_id BIGINT NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE `order` (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  user_id BIGINT NOT NULL,
  status VARCHAR(32) NOT NULL
);

CREATE TABLE payment (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  user_id BIGINT NOT NULL,
  status VARCHAR(20) NOT NULL
);

CREATE TABLE complaint (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  user_id BIGINT NOT NULL,
  status VARCHAR(20) NOT NULL
);
